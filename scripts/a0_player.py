#!/usr/bin/env python3
"""A0 — build a self-contained karaoke HTML page from word timings.

Why self-contained: browsers block `fetch()` of a local .vtt/JSON from
`file://`, so a page that loads its timings at runtime works only behind a
server. This inlines the timings and points the <audio> at the stem by relative
path (which *does* work from `file://`), so the page opens with a double-click.

Usage
-----
    python scripts/a0_player.py \
        --words results/a0a.words.json \
        --audio work/separated/htdemucs/<name>/vocals.wav \
        --out   player/a0a.html \
        --title "Ajam — Lamiyat Alshanfara (A0a)"
"""
from __future__ import annotations

import argparse
import html
import json
import os
from pathlib import Path

TEMPLATE = """<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<title>__TITLE__</title>
<style>
  :root { color-scheme: dark; }
  body { margin:0; background:#12141a; color:#dfe3ea;
         font:16px/1.9 system-ui,-apple-system,"Segoe UI",sans-serif; }
  header { padding:14px 18px; border-bottom:1px solid #262b36;
           position:sticky; top:0; background:#12141a; z-index:2; }
  h1 { font-size:15px; margin:0 0 8px; font-weight:600; letter-spacing:.02em; }
  audio { width:100%; }
  #meta { font-size:12px; color:#8b93a3; margin-top:8px; }
  main { padding:22px 18px 45vh; max-width:900px; margin:0 auto;
         direction:rtl; text-align:center; font-size:27px; }
  .w { padding:.08em .12em; border-radius:5px; transition:background .08s, color .08s; }
  .w.on { background:#ffd34d; color:#15171d; font-weight:600; }
  .w.done { color:#9aa3b4; }
  .sep { display:inline-block; width:.45em; }
  .off { direction:ltr; text-align:center; color:#6a7284; font-size:12px; margin-top:18px; }
</style></head><body>
<header>
  <h1>__TITLE__</h1>
  <audio id="a" controls preload="metadata" src="__AUDIO__"></audio>
  <div id="meta"></div>
</header>
<main id="ly"></main>
<div class="off">aligned __N__ words &middot; model __MODEL__ &middot;
  __DIAC__ &middot; generated by scripts/a0_player.py</div>
<script>
const W = __WORDS__;
const a = document.getElementById('a'), ly = document.getElementById('ly');
const meta = document.getElementById('meta');
const spans = [];
W.forEach((w, i) => {
  const s = document.createElement('span');
  s.className = 'w'; s.textContent = w.w; s.dataset.i = i;
  ly.appendChild(s); spans.push(s);
  const sep = document.createElement('span'); sep.className = 'sep'; sep.textContent=' ';
  ly.appendChild(sep);
});
let cur = -1;
function tick() {
  const t = a.currentTime;
  let idx = -1;
  for (let i = 0; i < W.length; i++) if (W[i].s <= t) idx = i; else break;
  if (idx !== cur) {
    if (cur >= 0 && spans[cur]) { spans[cur].classList.remove('on'); spans[cur].classList.add('done'); }
    cur = idx;
    if (idx >= 0 && spans[idx]) {
      spans[idx].classList.add('on');
      spans[idx].scrollIntoView({block:'center', behavior:'smooth'});
    }
  }
  meta.textContent = `${t.toFixed(2)}s  /  word ${cur+1} of ${W.length}` +
    (cur >= 0 ? `  ·  "${W[cur].w}" ${W[cur].s.toFixed(2)}–${W[cur].e.toFixed(2)}s` : '');
  requestAnimationFrame(tick);
}
requestAnimationFrame(tick);
</script></body></html>
"""


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--words", required=True, help="word-timings JSON from a0_align.py")
    ap.add_argument("--audio", required=True, help="path to the audio the page should play")
    ap.add_argument("--out", required=True, help="HTML file to write")
    ap.add_argument("--title", default="A0 — word-level karaoke")
    args = ap.parse_args(argv)

    data = json.loads(Path(args.words).read_text(encoding="utf-8"))
    words = [{"w": w["word"], "s": w["start"], "e": w["end"]} for w in data["words"]]

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    # relative path from the page to the audio, so the page is portable
    rel = os.path.relpath(Path(args.audio).resolve(), out.resolve().parent)

    diac = "diacritics stripped for alignment" if data.get(
        "stripped_diacritics") else "diacritics kept"
    html_text = (TEMPLATE
                 .replace("__TITLE__", html.escape(args.title))
                 .replace("__AUDIO__", html.escape(rel))
                 .replace("__WORDS__", json.dumps(words, ensure_ascii=False))
                 .replace("__N__", str(len(words)))
                 .replace("__MODEL__", html.escape(str(data.get("model", "?"))))
                 .replace("__DIAC__", diac))
    out.write_text(html_text, encoding="utf-8")
    print(f"wrote {out}  ({len(words)} words, audio -> {rel})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
