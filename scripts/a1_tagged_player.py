#!/usr/bin/env python3
"""A1 — re-render karaoke players with the caption's section tags kept.

A1 drops `[Verse 1 | ...]` tags **before** forced alignment: they are not sung,
and letting them through would put words in the CTC target. The tags are still
useful while reviewing a render, and their position survives the drop: walk the
original caption, keep tags as events, keep exactly the lyric lines A1 kept
(any line with an Arabic letter), and the line order matches
`<song>.words.json`'s `lines` one-to-one.

This script rewrites only `<song>.player.html`; word timings and the
`.srt`/`.vtt` cues are untouched. It does two review-oriented things:

  * **tags as dividers** — `[Chorus | intense ...]` becomes a labelled block
    (`CHORUS` plus the description) above the words it introduces;
  * **highlight ends on silence** — the forced path sometimes gives a word the
    following instrumental, so a naive player keeps it lit for 15–25 s. The
    display end is trimmed against the vocal stem's energy; the JSON keeps the
    aligner's end times.

Usage
-----
    # one song
    python scripts/a1_tagged_player.py \
        --words results/a1/<run>/<song>.words.json \
        --lyrics prompts/<name>_lyrics.txt

    # a whole run: match <name>_<seed>.words.json to prompts/<name>_lyrics.txt
    python scripts/a1_tagged_player.py \
        --dir results/a1/<run> --lyrics-dir /path/to/run/prompts

    # keep the raw aligned ends, and record section metadata in the JSON
    python scripts/a1_tagged_player.py --dir ... --lyrics-dir ... \
        --no-trim --annotate

Batch matching is the same rule A1 uses for prompts: the longest lyrics stem
that equals the song name or prefixes it at an `_` boundary.
"""
from __future__ import annotations

import argparse
import html
import json
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from a0_lyrics import EDGE_PUNCT  # noqa: E402

ARABIC_RE = re.compile(r"[\u0621-\u064a\u0671-\u06d3]")
SECTION_RE = re.compile(r"^\s*\[(.*)\]\s*$")
AUDIO_SUFFIXES = (".mp3", ".wav", ".flac")

