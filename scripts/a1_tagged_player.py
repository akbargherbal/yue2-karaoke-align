# --- caption structure -----------------------------------------------------

def parse_events(lyrics_text: str) -> list[dict]:
    """Ordered tags + lyric lines, using A1's line filter and word rules."""
    events: list[dict] = []
    gap = False
    for raw in lyrics_text.splitlines():
        s = raw.strip()
        if not s:
            gap = True
            continue
        m = SECTION_RE.match(s)
        if m:
            tag = m.group(1).strip()
            # `[Lyrics]` is A1's block marker, not a section heading.
            if tag and tag.lower() != "lyrics":
                events.append({"t": "tag", "text": tag})
            gap = False
            continue
        # Same rule as a1_align_run.lyric_structure: no Arabic letter -> not sung.
        if not ARABIC_RE.search(s):
            continue
        tokens = [t.strip(EDGE_PUNCT) for t in s.split()]
        if not [t for t in tokens if t]:
            continue
        events.append({"t": "line", "text": s, "gap": gap})
        gap = False
    return events


def split_tag(text: str) -> tuple[str, str]:
    if "|" in text:
        label, desc = text.split("|", 1)
        return label.strip(), desc.strip()
    return text.strip(), ""


def match_lyrics(song: str, files: list[Path]) -> Path | None:
    """Longest `<name>_lyrics.txt` / `<name>.txt` that prefixes the song."""
    best: tuple[int, Path] | None = None
    for path in files:
        stem = path.stem
        if stem.endswith("_lyrics"):
            stem = stem[: -len("_lyrics")]
        if song == stem or song.startswith(stem + "_"):
            if best is None or len(stem) > best[0]:
                best = (len(stem), path)
    return best[1] if best else None


def blocks_for(record: dict, events: list[dict]) -> list[dict]:
    """Interleave tag/gap/word blocks; every word must map to a lyric line."""
    lines = record.get("lines") or []
    line_events = [e for e in events if e["t"] == "line"]
    if len(line_events) != len(lines):
        raise ValueError(
            f"{record['song']}: lyrics file has {len(line_events)} sung lines, "
            f"words.json has {len(lines)} (wrong lyrics file?)")
    if any("line" not in w for w in record["words"]):
        raise ValueError(f"{record['song']}: words have no line index; "
                         "re-run A1 (line mapping failed)")

    by_line: dict[int, list[int]] = {}
    for i, w in enumerate(record["words"]):
        by_line.setdefault(w["line"], []).append(i)

    blocks: list[dict] = []
    li = 0
    for e in events:
        if e["t"] == "tag":
            label, desc = split_tag(e["text"])
            blocks.append({"t": "tag", "label": label, "desc": desc})
            continue
        if e["gap"] and blocks and blocks[-1]["t"] == "words":
            blocks.append({"t": "gap"})
        blocks.append({"t": "words",
                       "br": bool(blocks) and blocks[-1]["t"] == "words",
                       "words": by_line.get(li, [])})
        li += 1

    # Optional metadata for downstream tools; the player does not need it.
    section = None
    li = 0
    for e in events:
        if e["t"] == "tag":
            section = split_tag(e["text"])[0]
            continue
        lines[li]["section"] = section
        lines[li]["gap"] = bool(e["gap"])
        li += 1
    return blocks


# --- display-end trimming --------------------------------------------------

def vocal_rms(stem: Path, hop_s: float = 0.05):
    """50 ms RMS envelope of the vocal stem (mono)."""
    import numpy as np
    import soundfile as sf

    y, sr = sf.read(str(stem), dtype="float32", always_2d=False)
    if getattr(y, "ndim", 1) > 1:
        y = y.mean(axis=1)
    n = max(1, int(hop_s * sr))
    frames = len(y) // n
    rms = np.sqrt((y[: frames * n].reshape(frames, n) ** 2).mean(axis=1) + 1e-12)
    return rms, hop_s


def display_end(rms, hop: float, start: float, end: float,
                silence_s: float = 0.6, frac: float = 0.15,
                floor: float = 0.008) -> float:
    """End the highlight at the first sustained quiet stretch after `start`."""
    import numpy as np

    if end <= start:
        return end
    a = int(start / hop)
    b = min(len(rms), int(end / hop))
    if b <= a:
        return end
    head = rms[a: min(b, a + 8)]          # first 0.4 s sets the local level
    thr = max(floor, frac * float(np.percentile(head, 80)))
    need = max(2, int(round(silence_s / hop)))
    run = 0
    for i in range(a, b):
        if rms[i] < thr:
            run += 1
            if run >= need:
                cut = (i - need + 1) * hop
                return round(max(start + 0.35, min(end, cut)), 2)
        else:
            run = 0
    return round(end, 2)


# --- render ----------------------------------------------------------------

def find_audio(record: dict, out_dir: Path, override: str | None) -> Path:
    candidates: list[Path] = []
    if override:
        candidates.append(Path(override))
    if record.get("audio"):
        candidates.append(Path(record["audio"]))
    for suffix in AUDIO_SUFFIXES:
        candidates.append(out_dir / f"{record['song']}{suffix}")
    for cand in candidates:
        if cand.is_file():
            return cand
    raise FileNotFoundError(
        f"{record['song']}: audio not found (pass --audio, or put the mix "
        f"beside the player as {record['song']}.mp3)")


def render(record: dict, blocks: list[dict], out: Path, audio: Path,
           rms=None, hop: float = 0.05, trim: bool = True) -> int:
    words = []
    trimmed = 0
    for w in record["words"]:
        item = {"w": w["word"], "s": w["start"], "e": w["end"]}
        if trim and rms is not None:
            de = display_end(rms, hop, w["start"], w["end"])
            if de < w["end"] - 0.3:
                item["de"] = de
                trimmed += 1
        words.append(item)

    rel = os.path.relpath(audio.resolve(), out.resolve().parent)
    title = f"{record['song']} — {record['n_words_aligned']} words"
    diac = ("diacritics stripped for alignment" if record.get("stripped_diacritics")
            else "diacritics kept")
    text = (TEMPLATE
            .replace("__TITLE__", html.escape(title))
            .replace("__AUDIO__", html.escape(rel))
            .replace("__WORDS__", json.dumps(words, ensure_ascii=False))
            .replace("__BLOCKS__", json.dumps(blocks, ensure_ascii=False))
            .replace("__N__", str(len(words)))
            .replace("__MODEL__", html.escape(str(record.get("model", "?"))))
            .replace("__DIAC__", diac))
    out.write_text(text, encoding="utf-8")
    return trimmed


def one(words_path: Path, lyrics_path: Path, out_path: Path | None,
        args) -> tuple[int, int]:
    record = json.loads(words_path.read_text(encoding="utf-8"))
    events = parse_events(lyrics_path.read_text(encoding="utf-8"))
    blocks = blocks_for(record, events)

    out_dir = words_path.parent
    audio = find_audio(record, out_dir, args.audio)
    page = out_path or out_dir / f"{record['song']}.player.html"

    rms = hop = None
    if not args.no_trim:
        stem = Path(args.stem) if args.stem else Path(record.get("stem") or "")
        if stem.is_file():
            rms, hop = vocal_rms(stem)
        else:
            print(f"[tags] {record['song']}: no vocal stem, trim disabled",
                  file=sys.stderr)

    trimmed = render(record, blocks, page, audio, rms=rms, hop=hop or 0.05,
                     trim=not args.no_trim)

    if args.annotate:
        words_path.write_text(
            json.dumps(record, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8")

    tags = sum(1 for b in blocks if b["t"] == "tag")
    print(f"{record['song']}: {tags} tags · {len(record['words'])} words · "
          f"{trimmed} trimmed · {page}")
    return tags, trimmed


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--words", help="one <song>.words.json")
    ap.add_argument("--lyrics", help="the caption/lyrics file for --words")
    ap.add_argument("--dir", help="an A1 output dir (batch mode)")
    ap.add_argument("--lyrics-dir", help="dir of prompt/lyrics .txt files")
    ap.add_argument("--audio", help="mix to play (default: record audio or <song>.mp3)")
    ap.add_argument("--out", help="player path (single-song mode only)")
    ap.add_argument("--stem", help="vocal stem for the display-end trim")
    ap.add_argument("--no-trim", action="store_true",
                    help="use the aligned word ends as-is")
    ap.add_argument("--annotate", action="store_true",
                    help="write section/gap metadata into the .words.json lines")
    args = ap.parse_args(argv)

    single = bool(args.words or args.lyrics)
    batch = bool(args.dir or args.lyrics_dir)
    if single == batch:
        ap.error("use either --words + --lyrics, or --dir + --lyrics-dir")
    if single and not (args.words and args.lyrics):
        ap.error("--words and --lyrics go together")
    if batch and not (args.dir and args.lyrics_dir):
        ap.error("--dir and --lyrics-dir go together")
    if args.out and batch:
        ap.error("--out is single-song only")

    if single:
        try:
            one(Path(args.words), Path(args.lyrics),
                Path(args.out) if args.out else None, args)
        except (OSError, ValueError) as e:  # noqa: BLE001
            print(f"[tags] {e}", file=sys.stderr)
            return 1
        return 0

    lyrics_files = sorted(Path(args.lyrics_dir).glob("*.txt"))
    if not lyrics_files:
        ap.error(f"no .txt files in --lyrics-dir {args.lyrics_dir}")
    failures = 0
    for words_path in sorted(Path(args.dir).glob("*.words.json")):
        song = words_path.name[: -len(".words.json")]
        lyrics = match_lyrics(song, lyrics_files)
        if lyrics is None:
            print(f"[tags] {song}: no lyrics in {args.lyrics_dir} "
                  "(name must equal the song or prefix it at '_')",
                  file=sys.stderr)
            failures += 1
            continue
        try:
            one(words_path, lyrics, None, args)
        except (OSError, ValueError) as e:  # noqa: BLE001
            print(f"[tags] {song}: {e}", file=sys.stderr)
            failures += 1
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
